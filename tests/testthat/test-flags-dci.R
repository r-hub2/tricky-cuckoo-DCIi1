test_that("flag weighting repairs negative terminal indexing and exposes run semantics", {
  expect_equal(DCIi1:::flagwtg(c(0, -2, -3, -4)), c(0, -9, 0, 0))
  expect_equal(DCIi1:::flagwtg(c(0, 2, 3, 4)), c(0, 9, 0, 0))
  expect_equal(DCIi1:::flagwtg(c(0, 2, 3, 0, -2, -3, 0)), c(0, 5, 0, 0, -5, 0, 0))
  expect_equal(DCIi1:::flagwtg(numeric()), numeric())
  expect_equal(DCIi1:::flagwtg(1), 0)
  expect_equal(DCIi1:::flagwtg(c(0, 2)), c(0, 2))
  expect_equal(DCIi1:::flagwtg(c(0, 2, 0)), c(0, 2, 0))
  expect_equal(DCIi1:::flagwtg(c(2, 0), method = "runs"), c(2, 0))
  expect_equal(DCIi1:::flagwtg(c(2, 2, -3, -3), method = "runs"), c(0, 4, 0, -6))
  expect_equal(DCIi1:::flagwtg(c(0, 2, 3, 0), ctof = 1), c(0, 3, 0, 0))
  weights <- numeric(99); weights[c(2, 5, 8, 20, 50)] <- 1
  p <- DCIi1:::.prune_flags(weights, 22)
  flags <- which(p != 0); gaps <- diff(c(0, flags, 99))
  expect_true(all(head(gaps, -1) + tail(gaps, -1) >= 22))
  expect_equal(DCIi1:::.prune_flags(numeric(30), 22), numeric(30))
})

test_that("DCI evaluates fixed neighboring flags with correct global indices", {
  set.seed(106)
  x <- rnorm(160) + rep(c(0, 4, -3, 1), c(50, 15, 15, 80))
  a <- dcii1(x)
  expect_identical(names(a), c("Flag", "Direction", "pvalue", "istatistic", "etavec", "Magnitude"))
  expect_gt(nrow(a), 1)
  boundaries <- c(0, a$Flag, length(x))
  for (j in seq_len(nrow(a))) {
    b <- i1_test(x[seq.int(boundaries[j] + 1, boundaries[j + 2])], calibration = "none")
    expect_equal(a$pvalue[j], b$pvalue)
    expect_equal(a$istatistic[j], b$i1)
    expect_equal(a$etavec[j], boundaries[j] + b$etahat)
    expect_equal(a$Magnitude[j], b$cpmag)
  }
  expect_true(all(is.na(a$pvalue)))
  expect_equal(change_points(a), sort(unique(a$etavec)))
  expect_error(dcii1(x, output = "accepted"), "unused argument")
  expect_error(change_points(a, alpha = .1), "unused argument")
  empty <- dcii1(x, r1 = 1e20)
  expect_equal(nrow(empty), 0L)
  expect_type(empty$Flag, "double")
  expect_type(empty$Direction, "character")
  expect_length(change_points(empty), 0)
  local <- dcii1(x, nbrhudfracleni1 = .2)
  expect_false(identical(plain(a), plain(local)))
  expect_error(change_points(1), "dcii1 result")
})
